-- Professor appointment requests (Prototype 3).
-- Requests are not confirmed professor bookings.

CREATE TABLE IF NOT EXISTS appointments (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id INTEGER NOT NULL
        REFERENCES students(student_id),

    instructor_id INTEGER NOT NULL
        REFERENCES instructors(instructor_id),

    appointment_date DATE NOT NULL,

    appointment_time TIME NOT NULL,

    reason VARCHAR(300) NOT NULL
        CHECK (length(trim(reason)) BETWEEN 1 AND 300),

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_appointments_student
    ON appointments(student_id);

CREATE INDEX IF NOT EXISTS idx_appointments_instructor_date
    ON appointments(instructor_id, appointment_date);
