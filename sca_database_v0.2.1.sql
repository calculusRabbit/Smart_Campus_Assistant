CREATE TABLE IF NOT EXISTS Authentications (
	authentication_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	student_id INTEGER NOT NULL REFERENCES Students(student_id) ON DELETE CASCADE,
	status TEXT NOT NULL CHECK(status IN ('pending', 'approved', 'denied')),
	documents TEXT[] CHECK(CARDINALITY(documents)<=5),
	admin_message TEXT CHECK(LENGTH(admin_message)<=250),
	submitted_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	reviewed_time TIMESTAMPTZ CHECK(reviewed_time >= submitted_time), -- = for auto-approval
	last_resend TIMESTAMPTZ,
	resend_count INTEGER DEFAULT 0 CHECK(resend_count>=0)
);

--auto-delete student authentication documents after review is finished + increment denied counter if needed
CREATE OR REPLACE FUNCTION delete_auth_documents()
RETURNS TRIGGER AS $$
BEGIN
    NEW.documents := NULL;
    IF NEW.status = 'denied' THEN
		UPDATE Students 
        SET account_denied = account_denied+1 
        WHERE student_id = NEW.student_id;
    END IF;
	
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_delete_auth_docs
BEFORE UPDATE ON Authentications
FOR EACH ROW
	WHEN (NEW.status IN ('approved', 'denied') AND OLD.status = 'pending')
	EXECUTE FUNCTION delete_auth_documents();




